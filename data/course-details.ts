export const courseSlugs = courseDetails.map((d) => d.slug);

export function getCourseBySlug(
  slug: string,
): { course: Course; detail: CourseDetail } | null {
  const course = courses.find((c) => c.slug === slug);
  const detail = courseDetails.find((d) => d.slug === slug);
  return course && detail ? { course, detail } : null;
}
